// High-Performance Native SQLite Database for The Global Chronicle
const { DatabaseSync } = require('node:sqlite');
const fs = require('fs');
const path = require('path');

const DB_DIR = path.join(__dirname, '..', 'data');
if (!fs.existsSync(DB_DIR)) {
  fs.mkdirSync(DB_DIR, { recursive: true });
}

const DB_PATH = path.join(DB_DIR, 'chronicle.db');
const db = new DatabaseSync(DB_PATH);

// Initialize schema
db.exec(`
  CREATE TABLE IF NOT EXISTS articles (
    id TEXT PRIMARY KEY,
    slug TEXT UNIQUE,
    title TEXT NOT NULL,
    category TEXT NOT NULL,
    leadHero INTEGER DEFAULT 0,
    featured INTEGER DEFAULT 0,
    trendingRank INTEGER,
    author_name TEXT,
    author_role TEXT,
    author_avatar TEXT,
    publishedAt TEXT NOT NULL,
    readTime TEXT,
    coverImage TEXT,
    coverCaption TEXT,
    summary TEXT,
    content TEXT,
    tags TEXT,
    likes INTEGER DEFAULT 0,
    claps INTEGER DEFAULT 0,
    commentsCount INTEGER DEFAULT 0,
    autoGenerated INTEGER DEFAULT 0,
    trendingVelocity REAL DEFAULT 85.0,
    seoTitle TEXT,
    metaDescription TEXT,
    focusKeywords TEXT,
    seoScore INTEGER DEFAULT 95,
    schemaJsonLd TEXT,
    sourceUrl TEXT
  );

  CREATE INDEX IF NOT EXISTS idx_articles_category ON articles(category);
  CREATE INDEX IF NOT EXISTS idx_articles_published ON articles(publishedAt DESC);
  CREATE INDEX IF NOT EXISTS idx_articles_slug ON articles(slug);

  CREATE TABLE IF NOT EXISTS agent_logs (
    id INTEGER PRIMARY KEY AUTOINCREMENT,
    timestamp TEXT NOT NULL,
    type TEXT NOT NULL,
    message TEXT NOT NULL
  );
`);

/**
 * Maps raw database row back to complete Article object
 */
function rowToArticle(row) {
  if (!row) return null;
  return {
    id: row.id,
    slug: row.slug,
    title: row.title,
    category: row.category,
    leadHero: Boolean(row.leadHero),
    featured: Boolean(row.featured),
    trendingRank: row.trendingRank,
    author: {
      name: row.author_name || "Staff Correspondent",
      role: row.author_role || "World Bureau",
      avatar: row.author_avatar || "https://images.unsplash.com/photo-1534528741775-53994a69daeb?auto=format&fit=crop&w=200&q=80"
    },
    publishedAt: row.publishedAt,
    readTime: row.readTime,
    coverImage: row.coverImage,
    coverCaption: row.coverCaption,
    summary: row.summary,
    content: row.content,
    tags: row.tags ? JSON.parse(row.tags) : [],
    likes: row.likes || 0,
    claps: row.claps || 0,
    commentsCount: row.commentsCount || 0,
    autoGenerated: Boolean(row.autoGenerated),
    trendingVelocity: row.trendingVelocity || 85.0,
    seo: {
      title: row.seoTitle || row.title,
      metaDescription: row.metaDescription || row.summary,
      focusKeywords: row.focusKeywords ? JSON.parse(row.focusKeywords) : [],
      score: row.seoScore || 95,
      schemaJsonLd: row.schemaJsonLd ? JSON.parse(row.schemaJsonLd) : null
    },
    sourceUrl: row.sourceUrl
  };
}

/**
 * Insert or replace article in SQLite
 */
function insertArticle(art) {
  const insertStmt = db.prepare(`
    INSERT OR REPLACE INTO articles (
      id, slug, title, category, leadHero, featured, trendingRank,
      author_name, author_role, author_avatar,
      publishedAt, readTime, coverImage, coverCaption,
      summary, content, tags, likes, claps, commentsCount,
      autoGenerated, trendingVelocity, seoTitle, metaDescription,
      focusKeywords, seoScore, schemaJsonLd, sourceUrl
    ) VALUES (
      ?, ?, ?, ?, ?, ?, ?,
      ?, ?, ?,
      ?, ?, ?, ?,
      ?, ?, ?, ?, ?, ?,
      ?, ?, ?, ?,
      ?, ?, ?, ?
    )
  `);

  insertStmt.run(
    art.id,
    art.slug,
    art.title,
    art.category,
    art.leadHero ? 1 : 0,
    art.featured ? 1 : 0,
    art.trendingRank || null,
    art.author?.name || "Staff Correspondent",
    art.author?.role || "Bureau Reporter",
    art.author?.avatar || "",
    art.publishedAt || new Date().toISOString(),
    art.readTime || "5 min read",
    art.coverImage || "",
    art.coverCaption || "",
    art.summary || "",
    art.content || "",
    JSON.stringify(art.tags || []),
    art.likes || 0,
    art.claps || 0,
    art.commentsCount || 0,
    art.autoGenerated ? 1 : 0,
    art.trendingVelocity || 88.5,
    art.seo?.title || art.title,
    art.seo?.metaDescription || art.summary,
    JSON.stringify(art.seo?.focusKeywords || art.tags || []),
    art.seo?.score || 95,
    art.seo?.schemaJsonLd ? JSON.stringify(art.seo.schemaJsonLd) : null,
    art.sourceUrl || ""
  );

  return art;
}

/**
 * Fetch all articles ordered by date
 */
function getAllArticles() {
  const stmt = db.prepare(`SELECT * FROM articles ORDER BY publishedAt DESC`);
  const rows = stmt.all();
  return rows.map(rowToArticle);
}

/**
 * Fetch single article by ID
 */
function getArticleById(id) {
  const stmt = db.prepare(`SELECT * FROM articles WHERE id = ?`);
  const row = stmt.get(id);
  return rowToArticle(row);
}

/**
 * Fetch single article by Slug
 */
function getArticleBySlug(slug) {
  const stmt = db.prepare(`SELECT * FROM articles WHERE slug = ?`);
  const row = stmt.get(slug);
  return rowToArticle(row);
}

/**
 * Fetch sitemap URLs
 */
function getSitemapEntries() {
  const stmt = db.prepare(`SELECT slug, publishedAt, category FROM articles ORDER BY publishedAt DESC LIMIT 500`);
  return stmt.all();
}

/**
 * Log telemetry in database
 */
function logTelemetry(type, message) {
  const stmt = db.prepare(`INSERT INTO agent_logs (timestamp, type, message) VALUES (?, ?, ?)`);
  stmt.run(new Date().toISOString(), type, message);
}

function getRecentLogs(limit = 20) {
  const stmt = db.prepare(`SELECT * FROM agent_logs ORDER BY id DESC LIMIT ?`);
  return stmt.all(limit);
}

// Seed initial articles into SQLite from data/articles.json if empty
function autoMigrateFromJson() {
  const countRow = db.prepare(`SELECT COUNT(*) as count FROM articles`).get();
  if (countRow.count === 0) {
    console.log('[Database] Migrating existing articles into SQLite...');
    const jsonPath = path.join(DB_DIR, 'articles.json');
    if (fs.existsSync(jsonPath)) {
      try {
        const articles = JSON.parse(fs.readFileSync(jsonPath, 'utf8'));
        articles.forEach(art => insertArticle(art));
        console.log(`[Database] Successfully migrated ${articles.length} articles to SQLite!`);
      } catch (e) {
        console.error('[Database] Migration warning:', e.message);
      }
    }
  }
}

autoMigrateFromJson();

module.exports = {
  db,
  insertArticle,
  getAllArticles,
  getArticleById,
  getArticleBySlug,
  getSitemapEntries,
  logTelemetry,
  getRecentLogs
};
